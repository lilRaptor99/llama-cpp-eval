# ----------------------------------------------------- formatting helpers

def _format_v2(x: float, _pos: int) -> str:
    """2-decimal tick formatter (e.g., 0.75) for the Jaccard colorbar."""
    return f"{x:.2f}"


def _format_v3(x: float, _pos: int) -> str:
    """3-decimal tick formatter (e.g., 0.108) for the JSD colorbar."""
    return f"{x:.3f}"


def _format_cell_sci(v: float, decimals: int) -> str:
    """Fixed-point above the rounding threshold, scientific below it.

    JSD is a divergence, so it collapses toward 0 as quantizations
    agree — and on the cross-quantization view it collapses HARD:
    40-67% of off-diagonal cells fall below 5e-4 (median ~1e-3, min
    ~1e-6). A plain `{v:.3f}` renders every one of those as the
    identical, and completely uninformative, string `0.000`.

    So: render in scientific notation exactly when the fixed-point
    form would round to zero, i.e. below half a unit in the last
    place. The switch is value-driven rather than
    `decimals`-driven, so a row reading

        0.000   1.2e-04   0.001   0.091

    carries strictly more information than a row of `0.000`s, and the
    decimal places that remain readable stay readable. Exact zero is
    kept as `0.000` rather than `0.0e+00` — it is a meaningful
    diagonal/off-diagonal value, not a missing measurement.
    """
    if not np.isfinite(v):
        return "nan"
    if v != 0.0 and abs(v) < 0.5 * 10.0 ** (-decimals):
        return f"{v:.1e}"
    return f"{v:.{decimals}f}"


def _fmt_cell_jaccard(v: float) -> str:
    """Cell formatter for the Jaccard row (2 decimals)."""
    return _format_cell_sci(v, 2)


def _fmt_cell_jsd(v: float) -> str:
    """Cell formatter for the JSD row (3 decimals + scientific fallback)."""
    return _format_cell_sci(v, 3)


# ------------------------------------------------------------------- helpers

def _load_one_quant_overview_safe(model_dir: Path, quant: str
                                    ) -> dict[str, Any] | None:
    """Wrapper around `paper_heatmaps._load_one_quant_overview` that
    also pulls the canonical publishable label for `quant` so the
    figure's tick labels match the rest of the paper.

    Returns the same dict as `_load_one_quant_overview` (with keys
    `arch`, `counts_total`, `tokens`) plus a `publish_label` field
    (the canonical paper-label for this quant), or None if the
    overview file is missing / corrupt / shape-mismatched.
    """
    try:
        arch, counts_total, tokens = _load_one_quant_overview(
            model_dir / quant / "overall" / "counts_total_overview.json"
        )
    except (ValueError, json.JSONDecodeError, OSError,
            UnicodeDecodeError) as e:
        print(f"[warn] {model_dir}/{quant}/overall/"
              f"counts_total_overview.json: {e}; skipping")
        return None
    return {
        "arch": arch,
        "counts_total": counts_total,
        "tokens": tokens,
        "publish_label": _QUANT_PUBLISH_OVERRIDES.get(
            quant, _publish_quant_label(quant)
        ),
        "quant_dir_name": quant,
    }


def _discover_quants(model_dir: Path,
                      only_quants: list[str] | None
                      ) -> list[dict[str, Any]]:
    """Discover all quant directories under `model_dir` that have a
    valid `overall/counts_total_overview.json`. Apply `--quants`
    filter if provided.

    Returns a list of per-quant records (sorted by `QUANT_PRIORITY`)
    with keys `arch`, `counts_total`, `tokens`, `publish_label`,
    `quant_dir_name`.
    """
    records: list[dict[str, Any]] = []
    if not model_dir.is_dir():
        return records
    for sub in sorted(p for p in model_dir.iterdir() if p.is_dir()):
        if not (sub / "overall" / "counts_total_overview.json").is_file():
            continue
        if only_quants and sub.name not in only_quants:
            continue
        loaded = _load_one_quant_overview_safe(model_dir, sub.name)
        if loaded is None:
            continue
        records.append(loaded)

    def _sort_key(rec: dict[str, Any]) -> tuple[int, str]:
        label = rec["publish_label"]
        if label in QUANT_PRIORITY:
            return (QUANT_PRIORITY.index(label), label)
        return (len(QUANT_PRIORITY), label)

    records.sort(key=_sort_key)
    return records


def _compute_model_cross_quant_matrices(model_dir: Path,
                                          only_quants: list[str] | None
                                          ) -> dict[str, Any] | None:
    """Compute the layer-averaged pairwise Jaccard and JSD matrices
    across all valid quantisations of one model.

    Returns a dict with keys:
      - `arch`: architecture (name, n_layer, n_expert, n_expert_used)
      - `quant_labels`: list of publishable quant labels (sorted)
      - `jaccard`: (N_q, N_q) layer-averaged Jaccard matrix
      - `jsd`: (N_q, N_q) layer-averaged JSD matrix

    Returns None when fewer than 2 quantisations load successfully
    (a cross-quant comparison needs >= 2 quants).
    """
    records = _discover_quants(model_dir, only_quants)
    if len(records) < 2:
        return None

    # All records should share arch (same model, same architecture).
    arch = records[0]["arch"]
    for rec in records[1:]:
        a = rec["arch"]
        if (a["n_layer"] != arch["n_layer"]
                or a["n_expert"] != arch["n_expert"]
                or a["n_expert_used"] != arch["n_expert_used"]):
            print(f"[warn] {rec['quant_dir_name']}: arch mismatch vs "
                  f"{records[0]['quant_dir_name']} (L={a['n_layer']} "
                  f"E={a['n_expert']} k={a['n_expert_used']} vs "
                  f"L={arch['n_layer']} E={arch['n_expert']} "
                  f"k={arch['n_expert_used']}); skipping")
            records = [r for r in records if r is not rec]
    if len(records) < 2:
        return None

    quant_labels = [r["publish_label"] for r in records]
    counts_list = [r["counts_total"] for r in records]
    L = arch["n_layer"]
    K_model = arch["n_expert_used"]
    jaccard = _layer_averaged_pairwise_jaccard(counts_list, K_model, L)
    jsd = _layer_averaged_js_divergence_matrix(counts_list)
    return {
        "arch": arch,
        "quant_labels": quant_labels,
        "jaccard": jaccard,
        "jsd": jsd,
    }


# ------------------------------------------------------------------- plot

def _draw_one_heatmap(ax, mat, labels, *, vmin, vmax, cmap,
                      cell_text_format: Callable[[float], str]
                      = _fmt_cell_jaccard,
                      cell_text_threshold: float = 0.5,
                      tick_label_fontsize: int = 8,
                      cell_text_fontsize: int = 6,
                      cell_text_color_above: str = "white",
                      cell_text_color_below: str = "black",
                      row_label: str | None = None,
                      row_label_fontsize: int = 10,
                      ) -> "matplotlib.image.AxesImage":
    """Render one heatmap into `ax` (no titles / no axis labels) and
    return the `AxesImage` so the caller can build a shared colorbar.

    If `row_label` is supplied, it is rendered as the subplot's
    y-axis label (vertical text in the gutter immediately to the
    left of the heatmap). The label takes zero horizontal space
    inside the heatmap, so it can identify each row without
    shrinking the cell area — readers instantly know which row is
    Jaccard Similarity vs. JS-divergence without consulting the caption.
    """
    if row_label is not None:
        ax.set_ylabel(row_label, fontsize=row_label_fontsize,
                       rotation=90, labelpad=8, va="center")

    N = len(labels)
    im = ax.imshow(mat, vmin=vmin, vmax=vmax, cmap=cmap, aspect="equal",
                   interpolation="nearest")
    if N > 0:
        ax.set_xticks(range(N))
        ax.set_xticklabels(labels, rotation=30, ha="right",
                           fontsize=tick_label_fontsize)
        ax.set_yticks(range(N))
        ax.set_yticklabels(labels, rotation=0, fontsize=tick_label_fontsize)
    else:
        ax.set_xticks([0])
        ax.set_xticklabels([""], fontsize=tick_label_fontsize)
        ax.set_yticks([0])
        ax.set_yticklabels([""], fontsize=tick_label_fontsize)
    ax.tick_params(axis="both", which="both", length=0)
    for spine in ax.spines.values():
        spine.set_visible(False)
    # Per-cell text. Threshold is relative to the colormap so cells
    # below the midpoint get one colour and cells above get the other;
    # works for both Jaccard (Blues, dark at top) and JSD (Blues_r,
    # dark at bottom).
    for i in range(mat.shape[0]):
        for j in range(mat.shape[1]):
            v = float(mat[i, j])
            vnorm = (v - vmin) / max(1e-12, (vmax - vmin))
            color = (cell_text_color_above if vnorm > cell_text_threshold
                     else cell_text_color_below)
            ax.text(j, i, cell_text_format(v), ha="center",
                    va="center", fontsize=cell_text_fontsize, color=color)
    return im


# ------------------------------------------------------------------- main

def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--results-dir", type=Path,
        default=Path("/mnt/data/results-llama-cpp"),
        help="Root results directory containing per-model subdirectories "
             "(default: /mnt/data/results-llama-cpp).",
    )
    parser.add_argument(
        "--models", action="append", default=None,
        help="Restrict to a subset of filesystem-safe model ids "
             "(repeatable). Default: the 4 hardcoded models. KEEP IN "
             "SYNC with cross_model_comparison.py::DEFAULT_MODELS so "
             "both figures show the same model set.",
    )
    parser.add_argument(
        "--quants", action="append", default=None,
        help="Restrict to a subset of quant subdirectories "
             "(repeatable). Default: all quants with valid "
             "counts_total_overview.json.",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=None,
        help="Output directory (default: <results-dir>/paper_heatmaps/"
             "cross_quantization).",
    )
    parser.add_argument(
        "--width-in", type=float, default=FIGURE_WIDTH_IN,
        help=f"Figure width in inches (default: {FIGURE_WIDTH_IN}).",
    )
    parser.add_argument(
        "--height-in", type=float, default=FIGURE_HEIGHT_IN,
        help=f"Figure height in inches (default: {FIGURE_HEIGHT_IN}).",
    )
    parser.add_argument(
        "--dpi", type=int, default=DPI,
        help=f"Output DPI (default: {DPI}).",
    )
    args = parser.parse_args()

    # Resolve the model set.
    if args.models:
        # Use a dict so the user can preserve the canonical short-name
        # ordering even when overriding the set.
        canonical = dict(DEFAULT_MODELS)
        models = [(m, canonical.get(m, m)) for m in args.models]
    else:
        models = list(DEFAULT_MODELS)

    # Resolve the output directory.
    out_dir = (args.output_dir if args.output_dir is not None
               else args.results_dir / "paper_heatmaps"
                     / "cross_quantization")
    out_dir.mkdir(parents=True, exist_ok=True)

    # ---- Step 1: load every model's cross-quant matrices.
    per_model: dict[str, dict[str, Any]] = {}
    for model_safe, short_name in models:
        model_dir = args.results_dir / model_safe
        if not model_dir.is_dir():
            print(f"[warn] {model_dir}: not found; skipping model "
                  f"{short_name}")
            continue
        data = _compute_model_cross_quant_matrices(model_dir, args.quants)
        if data is None:
            print(f"[warn] {model_dir}: <2 valid quantisations found; "
                  f"skipping model {short_name}")
            continue
        per_model[short_name] = {
            "model_safe": model_safe,
            "arch": data["arch"],
            "labels": data["quant_labels"],
            "jaccard": data["jaccard"],
            "jsd": data["jsd"],
        }
        print(f"[load] {short_name}: {data['arch']['name']} "
              f"L={data['arch']['n_layer']} E={data['arch']['n_expert']} "
              f"K_model={data['arch']['n_expert_used']}; "
              f"quants={data['quant_labels']}")

    if not per_model:
        raise SystemExit("[error] no models loaded successfully")

    n_cols = len(per_model)
    if n_cols < 1:
        raise SystemExit("[error] need at least 1 model")

    # ---- Step 2: shared JSD vmax is a fixed 0.5 (same convention as
    # the sibling cross_model_comparison.py script and the empirically
    # observed largest divergence across the result histograms). This
    # avoids the per-run global-max scan.
    jsd_vmax = 0.5
    print("[plan] JSD shared colorbar range: fixed 0 to 0.5 "
          "(empirical max across all result histograms; no per-run "
          "global scan needed)")

    # ---- Step 3: figure layout (2 rows x n_cols cols).
    # Reserve right margin for the per-row colorbar. With n_cols
    # subplots side-by-side, the per-subplot width is constrained so
    # the whole row + colorbar fits in --width-in inches. Subplot
    # height tracks subplot width so each N_q x N_q matrix stays
    # square (cells are square).
    cbar_width_in = 0.4
    grid_width_in = args.width_in - cbar_width_in
    subplot_width_in = grid_width_in / n_cols
    subplot_height_in = subplot_width_in * 0.85

    fig = plt.figure(figsize=(args.width_in, args.height_in), dpi=args.dpi)

    gs = fig.add_gridspec(
        nrows=2, ncols=n_cols + 1,
        width_ratios=[subplot_width_in] * n_cols + [cbar_width_in * 0.6],
        height_ratios=[subplot_height_in] * 2,
        left=0.04, right=0.98, top=0.92, bottom=0.08,
        wspace=0.02, hspace=0.08,
    )

    # ---- Step 4: render the Jaccard row (top).
    jaccard_axes = []
    jaccard_im = None
    for col, short_name in enumerate(per_model.keys()):
        ax = fig.add_subplot(gs[0, col])
        data = per_model[short_name]
        im = _draw_one_heatmap(
            ax, data["jaccard"], data["labels"],
            vmin=0.0, vmax=1.0, cmap="Blues",
            cell_text_format=_fmt_cell_jaccard,
            cell_text_threshold=0.5,
            cell_text_color_above="white",
            cell_text_color_below="black",
            tick_label_fontsize=8,
            cell_text_fontsize=6,
            # Row labels: only the leftmost column shows them so the
            # inner columns can keep their y-tick labels hidden without
            # the gutter text colliding with the cells.
            row_label=("Jaccard Similarity" if col == 0 else None),
        )
        ax.set_title(short_name, fontsize=9, pad=4)
        # Tick labels. x-tick labels (the quant names) are only
        # rendered on the BOTTOM row so readers scan the column
        # names once rather than seeing them under every subplot.
        # y-tick labels are only rendered on the LEFTMOST column of
        # each row — the row label in the gutter ("Jaccard
        # Similarity" / "JS divergence") handles row identification,
        # and the quant names on the y-axis are shown just once per
        # row.
        plt.setp(ax.get_xticklabels(), visible=False)
        if col == 0:
            # Leftmost column: shows y-tick labels (quant names)
            # AND the gutter row label. They live in different
            # gutters (left margin vs. just-left-of-axis), so they
            # coexist cleanly.
            ax.tick_params(axis="y", which="both", length=0)
        else:
            plt.setp(ax.get_yticklabels(), visible=False)
            ax.tick_params(axis="y", which="both", length=0)
        jaccard_axes.append(ax)
        jaccard_im = im

    # Per-row colorbar for Jaccard (right of the row).
    cax_jacc = fig.add_subplot(gs[0, n_cols])
    cb_jacc = fig.colorbar(jaccard_im, cax=cax_jacc,
                            fraction=1.0, pad=0.0)
    cb_jacc.ax.tick_params(labelsize=8, length=0)
    cb_jacc.outline.set_visible(False)
    cb_jacc.ax.yaxis.set_major_formatter(FuncFormatter(_format_v2))
    cb_jacc.set_ticks(np.linspace(0.0, 1.0, 6))

    # ---- Step 5: render the JSD row (bottom).
    jsd_axes = []
    jsd_im = None
    for col, short_name in enumerate(per_model.keys()):
        ax = fig.add_subplot(gs[1, col])
        data = per_model[short_name]
        im = _draw_one_heatmap(
            ax, data["jsd"], data["labels"],
            vmin=0.0, vmax=jsd_vmax, cmap="Blues_r",
            cell_text_format=_fmt_cell_jsd,
            cell_text_threshold=0.5,
            cell_text_color_above="black",
            cell_text_color_below="white",
            tick_label_fontsize=8,
            cell_text_fontsize=6,
            row_label=("JS divergence" if col == 0 else None),
        )
        # The JSD row shows the x-tick labels (quant names) — they
        # are the COLUMN identification for the whole figure. The
        # y-tick labels are only on the leftmost column of this
        # row; the gutter label (rendered by `_draw_one_heatmap`)
        # identifies the row metric.
        if col == 0:
            ax.tick_params(axis="y", which="both", length=0)
        else:
            plt.setp(ax.get_yticklabels(), visible=False)
            ax.tick_params(axis="y", which="both", length=0)
        jsd_axes.append(ax)
        jsd_im = im

    # Per-row colorbar for JSD (right of the row).
    cax_jsd = fig.add_subplot(gs[1, n_cols])
    cb_jsd = fig.colorbar(jsd_im, cax=cax_jsd, fraction=1.0, pad=0.0)
    cb_jsd.ax.tick_params(labelsize=8, length=0)
    cb_jsd.outline.set_visible(False)
    cb_jsd.ax.yaxis.set_major_formatter(FuncFormatter(_format_v3))
    cb_jsd.set_ticks(np.linspace(0.0, jsd_vmax, 6))

    # ---- Step 6: save the figure.
