#!/usr/bin/env python3
# type: ignore

"""Cross-model cross-quantization comparison figure for the MoE-routing paper.

Sibling peer of `cross_model_comparison.py` (which compares models on
the cross-DATASET Jaccard/JSD matrices). This script compares models
on the cross-QUANTIZATION Jaccard/JSD matrices: for each model, we
build the layer-averaged pairwise Jaccard and JS-divergence matrices
across that model's quantizations, then arrange them side-by-side as
a 2×N figure so reviewers can see at a glance whether quantisation
affects routing distribution uniformly across models or only some.

Layout:

    [OLMoE-1B ][Mixtral ][DeepSeek][Qwen3  ]   <- column titles (top)
    [ Jaccard row: N_q x N_q heatmap per model            ]   <- 1 colorbar
    [ JSD     row: N_q x N_q heatmap per model            ]   <- 1 colorbar

`N_q` is the number of valid quantisations discovered per model
(typically 2–4: Q2_K, Q4_K_M, optionally Q8_0 / F16 / F32, plus the
UnifRand baseline when `<model>/RANDOM/overall/...` exists).
Models with different `N_q` still appear in the same figure — each
subplot is sized so the cells fit; cell sizes vary modestly across
models (small N_q → bigger cells, large N_q → smaller cells), which
is fine for a cross-model comparison.

JSD colorbar uses a **fixed [0, 0.5] scale** (the empirically
observed largest possible divergence across the result histograms).
This avoids the per-run global-max pre-pass and keeps every cross-
model comparison on the identical scale without scanning every
quantization cell first. Same convention as the sibling
`cross_model_comparison.py` script.

The figure is sized for a double-column paper (~11in × 5.5in), 300
DPI, no titles / no axis labels beyond the model-name column titles
— readers get the quant label interpretation from the figure caption,
not the figure itself (saves horizontal space, same convention as
`cross_model_comparison.py`).

Output (under `<output-dir>/`, default
`<results-dir>/paper_heatmaps/cross_quantization/`):

  - `cross_quantization_grid.png`     the 2×N figure

The cross-quantisation summary table (mean ± std across quants for
each metric) and the per-model cross-quantisation comparison are NOT
produced by this script. The companion
`cross_quantization_table.py` produces the table; the per-model
single-figure view is generated by the per-cell helpers in
`paper_heatmaps.py` (which writes
`<model>__<quant>__jaccard_quant.png` and
`<model>__js_divergence_quant.png`).

Mathematical contract (identical to `paper_heatmaps.py` and the
existing eval-moe-overview Jaccard/JSD helpers):

  For each layer l and each pair of quants (q_a, q_b) of the same
  model m:
    A_q_K[l]  = top-K experts in quant q, layer l
                (descending count, ties -> ascending expert id)
  Jaccard_m(q_a, q_b) = |A_q_a ∩ A_q_b| / |A_q_a ∪ A_q_b|
                                                     averaged over layers
  JSD_m     (q_a, q_b) = Jensen-Shannon divergence of the marginal
                         routing distributions,
                                                     averaged over layers

We compute both at K = K_model (the natural choice; different quants
of the same model share K_model, so the matrices are directly
comparable).
"""

