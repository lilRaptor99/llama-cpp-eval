#!/usr/bin/env python3
# type: ignore

"""Publication-quality jaccard_global K-sweep plotter for the MoE-routing paper.

For one `(model, quant)` cell, renders a clean 2-row figure showing how
cross-dataset Jaccard varies with K (top-K experts per dataset):

    Row 1: generalized |∩|/|∪|  (strict consensus; drops fast on outliers)
    Row 2: mean pairwise Jaccard (smoother; captures average agreement)

Both rows share the same K axis and use thin per-layer traces with a
bold mean-across-layers line. K_model is marked with a vertical dotted
line; the diagonal y = 1.0 is shown as a faint dashed reference.

This is the publication-quality counterpart of
`eval-moe-overview/jaccard_sweep_from_cpp.py::jaccard_global.png`,
which overlays both metrics on a single plot with a multi-line title.
The 2-row stacked layout makes the relationship between strict consensus
and mean pairwise agreement immediately visible (the strict-consensus
curve is always ≤ the pairwise curve by definition, and the gap grows
as the datasets diverge); the shared K axis removes redundant labeling;
and the multi-line title / grid / legend are dropped per the paper
conventions used by `paper_heatmaps.py`.

Output (under `<output-dir>/`, default
`<cell-dir>/paper_jaccard_sweep/`):

  - `jaccard_global.png`     the 2-row paper figure (300 DPI, no titles)

No CSV outputs — single-responsibility script (figure only). The
underlying K-sweep CSV is generated by the sibling
`eval-moe-overview/jaccard_sweep_from_cpp.py` if needed.

Mathematical contract (identical to `jaccard_sweep_from_cpp.py`):

  For each layer l and K value:
    A_i_K[l]  = top-K experts in dataset i, layer l
                (descending count, ties -> ascending expert id)
    |∩|_K[l]  = |∩_i A_i_K[l]|              (intersection across datasets)
    |∪|_K[l]  = |∪_i A_i_K[l]|              (union across datasets)
    generalized Jaccard (strict consensus): |∩|_K[l] / |∪|_K[l]
    mean pairwise Jaccard:                  mean over all C(N, 2) pairs of
                                            |A_i ∩ A_j| / |A_i ∪ A_j|

  Edge cases (empty sets): 1.0 when all empty, 0.0 when only one
  non-empty — matches the convention in `paper_heatmaps._jaccard`.

Only the 5 real benchmarks (BBH / HumanEval / INCLUDE / MMLU / PopQA)
are compared; the optional `UniformRand` baseline loaded by
`cross_model_comparison._load_cell_counts` is filtered out so the
figure answers the same question as the existing
`jaccard_global.png` (which only sees `moe-*` directories).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np
import matplotlib.pyplot as plt

# Make the sibling `paper_heatmaps.py` and `cross_model_comparison.py`
# importable. All three files live in `examples/eval-heatmaps/` so
# Python's per-script sys.path entry resolves these imports without
# any setup.py / PYTHONPATH plumbing.
_SCRIPT_DIR = Path(__file__).resolve().parent
if str(_SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPT_DIR))

from paper_heatmaps import (  # noqa: E402
    _jaccard,
    _make_k_values,
    _safe_json_load,
    _top_k_set_for_layer,
)


# ----------------------------------------------------------------- constants

# Figure sizing (single-column paper).
FIGURE_WIDTH_IN: float = 5.0
FIGURE_HEIGHT_IN: float = 4.0
DPI: int = 300

# Color scheme. Thin per-layer traces are light blue with low alpha;
# the bold mean-across-layers line uses a darker navy. These match
# the convention used in `jaccard_sweep_from_cpp.py::jaccard_global.png`
# (the existing 120 DPI overview) so a reviewer reading both figures
# recognises the same colour-by-metric mapping.
LAYER_COLOR: str = "#4477aa"
LAYER_ALPHA: float = 0.18
LAYER_LINEWIDTH: float = 0.7
MEAN_COLOR: str = "#1f3a5f"
MEAN_LINEWIDTH: float = 2.4
K_MODEL_COLOR: str = "#888888"
REFERENCE_COLOR: str = "#cccccc"


# ---------------------------------------------------------- cell loading

def _load_moe_counts(cell_dir: Path
                      ) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    """Load every `moe-<ds>/expert_counts.json` under one cell.

    Same shape as `cross_model_comparison._load_cell_counts` but
    restricted to the `moe-*` directories only (no auto-aggregation
    of the random router baseline — the K-sweep is on real benchmarks
    only, matching the existing `jaccard_global.png` semantics).

    Uses `paper_heatmaps._safe_json_load` for corrupt-JSON recovery
    so the script degrades gracefully on partially-flushed files from
    an interrupted C++ run.

    Returns:
      counts: dict mapping publishable dataset label -> [L, E] int64
              array (the `aggregate.marginal_expert_counts` matrix).
      arch  : dict with keys `name`, `n_layer`, `n_expert`,
              `n_expert_used` (taken from the first dataset's JSON).
    """
    counts: dict[str, np.ndarray] = {}
    arch: dict[str, Any] | None = None
    warned: set[str] = set()
    for js_path in sorted(cell_dir.glob("moe-*/expert_counts.json")):
        ds_dir_name = js_path.parent.name  # e.g. "moe-mmlu"
        data = _safe_json_load(js_path)
        if data is None:
            if str(js_path) not in warned:
                warned.add(str(js_path))
                print(f"[warn] {js_path}: unable to load JSON "
                      f"(corrupted beyond recovery); skipping")
            continue
        arch_in = data.get("model_arch") or {}
        L = int(arch_in.get("n_layer", 0))
        E = int(arch_in.get("n_expert", 0))
        k = int(arch_in.get("n_expert_used", 0))
        if L <= 0 or E <= 0 or k <= 0:
            continue
        marginal = (data.get("aggregate") or {}).get(
            "marginal_expert_counts"
        )
        if marginal is None:
            continue
        m = np.asarray(marginal, dtype=np.int64)
        if m.shape != (L, E):
            if str(js_path) not in warned:
                warned.add(str(js_path))
                print(f"[warn] {js_path}: shape {m.shape} != "
                      f"({L}, {E}); skipping")
            continue
        # Match `cross_model_comparison._order_labels`: BBH / HumanEval /
        # INCLUDE / MMLU / PopQA in publishable form; fall back to
        # the dataset directory name verbatim for anything else.
        from paper_heatmaps import _publish_dataset_label  # local import
        publish_ds = _publish_dataset_label(ds_dir_name)
        counts[publish_ds] = m
        if arch is None:
            arch = {"name": arch_in.get("name", "unknown"),
                    "n_layer": L, "n_expert": E, "n_expert_used": k}
    if arch is None:
        raise SystemExit(f"[error] {cell_dir}: no usable datasets found")
    return counts, arch


# ---------------------------------------------------------- K-sweep math

def _generalized_jaccard(sets_list: list[set[int]]) -> float:
    """Generalized Jaccard for N>=1 sets:  |∩ A_i| / |∪ A_i|.

    "Strict consensus" measure — 1.0 iff every dataset has the *exact
    same* top-K set, drops fast if any dataset diverges. Returns:

      - 1.0 when all sets are empty (no data -> trivially agree)
      - 0.0 when only one set is non-empty (no comparison possible)
      - `len(intersection) / len(union)` in the general case

    Mirrors `jaccard_sweep_from_cpp._generalized_jaccard` exactly so
    the curves on the paper figure are bit-identical to the 120 DPI
    overview (modulo per-layer averaging).
    """
    non_empty = [s for s in sets_list if s]
    if not non_empty:
        return 1.0
    if len(non_empty) == 1:
        return 0.0
    inter = non_empty[0].copy()
    union = non_empty[0].copy()
    for s in non_empty[1:]:
        inter &= s
        union |= s
    if not union:
        return 1.0
    return len(inter) / len(union)


def _compute_k_sweep(counts: dict[str, np.ndarray], K_values: list[int],
                      L: int
                      ) -> tuple[dict[int, list[float]],
                                 dict[int, list[float]]]:
    """Compute the two Jaccard metrics at every (K, layer).

    Returns (jaccard_union, jaccard_pairwise_mean) where each is a
    dict mapping K -> list[float] of length L (one value per layer).
    """
    ds_names_sorted = sorted(counts.keys())
    N_ds = len(ds_names_sorted)

    # Pre-compute per-(ds, K, layer) top-K sets.
    top_k_sets: dict[str, dict[int, list[set[int]]]] = {}
    for ds in ds_names_sorted:
        c = counts[ds]
        top_k_sets[ds] = {
            K: [_top_k_set_for_layer(c, layer, K) for layer in range(L)]
            for K in K_values
        }

    jaccard_union: dict[int, list[float]] = {
        K: [0.0] * L for K in K_values
    }
    jaccard_pairwise_mean: dict[int, list[float]] = {
        K: [0.0] * L for K in K_values
    }
    for K in K_values:
        for layer in range(L):
            sets_at_kl = [top_k_sets[ds][K][layer] for ds in ds_names_sorted]
            jaccard_union[K][layer] = _generalized_jaccard(sets_at_kl)
            if N_ds >= 2:
                triu_vals = [
                    _jaccard(sets_at_kl[i], sets_at_kl[j])
                    for i in range(N_ds)
                    for j in range(i + 1, N_ds)
                ]
                jaccard_pairwise_mean[K][layer] = float(
                    np.mean(triu_vals)
                )
            else:
                jaccard_pairwise_mean[K][layer] = 1.0
    return jaccard_union, jaccard_pairwise_mean


# --------------------------------------------------------------- render

def render_paper_jaccard_global(cell_dir: Path, output_dir: Path,
                                  *, width_in: float, height_in: float,
                                  dpi: int, k_min: int, k_max_frac: float,
                                  num_ks: int,
                                  force: bool = False,
                                  ) -> dict[str, Any]:
    """Render the publication-quality jaccard_global sweep PNG.

    Returns a summary dict for stdout reporting. Skips when the
    sentinel `jaccard_global.png` already exists (unless `force=True`).
    """
    cell_dir = cell_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    out_png = output_dir / "jaccard_global.png"
    if out_png.exists() and not force:
        print(f"[skip] {out_png} exists; pass --force to regenerate")
        return {"cell_dir": str(cell_dir), "output_dir": str(output_dir),
                "skipped": True}

    counts, arch = _load_moe_counts(cell_dir)
    if len(counts) < 2:
        raise SystemExit(
            f"[error] {cell_dir}: <2 valid datasets found "
            f"(have {sorted(counts.keys())}); need >=2 for "
            f"cross-dataset Jaccard"
        )

    L = arch["n_layer"]
    E = arch["n_expert"]
    K_model = arch["n_expert_used"]
    K_values = _make_k_values(E, K_model, k_min, k_max_frac, num_ks)
    print(f"[load] {arch['name']} L={L} E={E} K_model={K_model}; "
          f"datasets={sorted(counts.keys())}; "
          f"K-sweep ({len(K_values)} values) = {K_values}")

    jaccard_union, jaccard_pairwise_mean = _compute_k_sweep(
        counts, K_values, L
    )

    K_arr = np.asarray(K_values, dtype=np.float64)
    union_per_layer = np.array(
        [jaccard_union[K] for K in K_values], dtype=np.float64
    ).T  # [L, n_K]
    pairwise_per_layer = np.array(
        [jaccard_pairwise_mean[K] for K in K_values], dtype=np.float64
    ).T  # [L, n_K]
    union_mean_curve = union_per_layer.mean(axis=0)
    pairwise_mean_curve = pairwise_per_layer.mean(axis=0)

    # ---- Render the 2-row figure ----
    # Stacked subplots, shared K axis (only the bottom row shows K
    # tick labels to save vertical space). No titles; minimal axis
    # labels; clean axes (no spines, no grid).
    fig, axes = plt.subplots(
        2, 1, figsize=(width_in, height_in), dpi=dpi, sharex=True,
    )

    for ax, per_layer, mean_curve, label in (
        (axes[0], union_per_layer, union_mean_curve,
         "generalized |∩|/|∪|"),
        (axes[1], pairwise_per_layer, pairwise_mean_curve,
         "mean pairwise Jaccard"),
    ):
        # Thin per-layer traces.
        for layer in range(L):
            ax.plot(K_arr, per_layer[layer],
                    color=LAYER_COLOR, alpha=LAYER_ALPHA,
                    linewidth=LAYER_LINEWIDTH)
        # Bold mean-across-layers line.
        ax.plot(K_arr, mean_curve,
                color=MEAN_COLOR, linewidth=MEAN_LINEWIDTH,
                marker="o", markersize=4)
        # K_model vertical marker.
        ax.axvline(K_model, color=K_MODEL_COLOR, linestyle=":",
                   linewidth=0.8)
        # Perfect-agreement horizontal reference.
        ax.axhline(1.0, color=REFERENCE_COLOR, linestyle="--",
                   linewidth=0.6)
        # Clean axes.
        ax.set_ylim(-0.02, 1.05)
        ax.tick_params(axis="both", length=0, labelsize=8)
        for spine in ax.spines.values():
            spine.set_visible(False)
        # Minimal in-axes label (replaces the multi-line title).
        ax.text(0.02, 0.95, label, transform=ax.transAxes,
                fontsize=9, va="top", ha="left", color="#222222")

    axes[1].set_xlabel("K", fontsize=9)
    axes[0].set_ylabel("Jaccard", fontsize=9)
    axes[1].set_ylabel("Jaccard", fontsize=9)

    fig.tight_layout()
    fig.savefig(out_png, dpi=dpi, bbox_inches="tight")
    plt.close(fig)
    print(f"[save] {out_png}")

    return {
        "cell_dir": str(cell_dir),
        "output_dir": str(output_dir),
        "arch": arch,
        "k_values": K_values,
        "n_datasets": len(counts),
        "skipped": False,
    }


# ------------------------------------------------------------------- CLI

def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--cell-dir", type=Path, required=True,
        help="Single (model, quant) cell directory containing "
             "moe-*/expert_counts.json files.",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=None,
        help="Output directory "
             "(default: <cell-dir>/paper_jaccard_sweep).",
    )
    parser.add_argument(
        "--width-in", type=float, default=FIGURE_WIDTH_IN,
        help=f"Figure width in inches (default: {FIGURE_WIDTH_IN}).",
    )
    parser.add_argument(
        "--height-in", type=float, default=FIGURE_HEIGHT_IN,
        help=f"Figure height in inches (default: {FIGURE_HEIGHT_IN}).",
    )
    parser.add_argument(
        "--dpi", type=int, default=DPI,
        help=f"Output DPI (default: {DPI}).",
    )
    parser.add_argument(
        "--k-min", type=int, default=1,
        help="Minimum K in the sweep (default: 1).",
    )
    parser.add_argument(
        "--k-max-frac", type=float, default=0.50,
        help="K_max = ceil(n_expert * k_max_frac) (default: 0.50). "
             "Same default as jaccard_sweep_from_cpp.py so the K-sweep "
             "grid lines up with the existing 120 DPI overview.",
    )
    parser.add_argument(
        "--num-ks", type=int, default=21,
        help="Number of K values in the linear sweep (default: 21).",
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Re-render even if jaccard_global.png already exists.",
    )
    args = parser.parse_args()

    if not args.cell_dir.is_dir():
        raise SystemExit(f"[error] {args.cell_dir} is not a directory")

    output_dir = (args.output_dir
                  if args.output_dir is not None
                  else args.cell_dir / "paper_jaccard_sweep")

    render_paper_jaccard_global(
        args.cell_dir, output_dir,
        width_in=args.width_in, height_in=args.height_in, dpi=args.dpi,
        k_min=args.k_min, k_max_frac=args.k_max_frac, num_ks=args.num_ks,
        force=args.force,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
